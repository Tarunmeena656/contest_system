import { useState, type FormEvent } from 'react';
import { api } from '../api';
import { typeLabel } from '../format';
import type { GenerateResponse, QuestionType } from '../types';
import { ErrorMessage, Message } from './Message';

interface Props {
  contestId: string;
  onSaved(count: number): void;
}

const allTypes: QuestionType[] = ['single-select', 'multi-select', 'true-false'];

// Ask the AI for a preview first, then store exactly what was previewed through
// the normal "add questions" endpoint, so the admin never saves unseen content.
export function GeneratePanel({ contestId, onSaved }: Props) {
  const [topic, setTopic] = useState('');
  const [difficulty, setDifficulty] = useState('medium');
  const [count, setCount] = useState(5);
  const [types, setTypes] = useState<QuestionType[]>(allTypes);
  const [preview, setPreview] = useState<GenerateResponse | null>(null);
  const [busy, setBusy] = useState<'generate' | 'save' | null>(null);
  const [error, setError] = useState<unknown>(null);
  const [notice, setNotice] = useState('');

  function toggleType(type: QuestionType) {
    setTypes((prev) => (prev.includes(type) ? prev.filter((t) => t !== type) : [...prev, type]));
  }

  async function generate(event: FormEvent) {
    event.preventDefault();
    setBusy('generate');
    setError(null);
    setNotice('');
    try {
      const res = await api.post<GenerateResponse>(`/contests/${contestId}/questions/generate`, {
        topic,
        difficulty,
        count,
        questionTypes: types,
        save: false,
      });
      setPreview(res);
    } catch (err) {
      setError(err);
    } finally {
      setBusy(null);
    }
  }

  async function save() {
    if (!preview) return;
    setBusy('save');
    setError(null);
    try {
      await api.post(`/contests/${contestId}/questions`, {
        questions: preview.questions.map((q) => ({
          type: q.type,
          text: q.text,
          options: q.options,
          correct_answers: q.correct_answers,
          explanation: q.explanation,
          points: q.points,
        })),
      });
      setNotice(`${preview.questions.length} questions added to the contest.`);
      onSaved(preview.questions.length);
      setPreview(null);
    } catch (err) {
      setError(err);
    } finally {
      setBusy(null);
    }
  }

  return (
    <div className="stack">
      <form onSubmit={generate} className="stack">
        <div className="row">
          <label>
            Topic
            <input
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              placeholder="JavaScript promises"
              required
              minLength={2}
            />
          </label>
          <label>
            Difficulty
            <select value={difficulty} onChange={(e) => setDifficulty(e.target.value)}>
              <option value="easy">Easy</option>
              <option value="medium">Medium</option>
              <option value="hard">Hard</option>
            </select>
          </label>
          <label>
            How many
            <input type="number" min={1} max={20} value={count} onChange={(e) => setCount(Number(e.target.value))} />
          </label>
        </div>
        <fieldset className="inline-options">
          <legend>Question types</legend>
          {allTypes.map((type) => (
            <label key={type} className="option small">
              <input type="checkbox" checked={types.includes(type)} onChange={() => toggleType(type)} />
              {typeLabel[type]}
            </label>
          ))}
        </fieldset>
        <div className="actions">
          <button type="submit" disabled={busy !== null || types.length === 0}>
            {busy === 'generate' ? 'Generating…' : 'Generate preview'}
          </button>
        </div>
      </form>

      <ErrorMessage error={error} />
      {notice && <Message kind="success">{notice}</Message>}

      {preview && (
        <div className="stack">
          <Message>
            {preview.generated} of {preview.requested} generated by the <strong>{preview.provider}</strong> provider
            {preview.rejected > 0 && `, ${preview.rejected} rejected by validation`}. Nothing is saved yet.
            {preview.provider === 'mock' &&
              ' The mock provider answers from a built-in question bank; set an API key for the live model.'}
          </Message>
          {preview.questions.map((q, index) => (
            <div key={index} className="question">
              <p>
                <span className="muted small">
                  {index + 1}. {typeLabel[q.type]} · {q.points} pt
                </span>
                <span className="question-text">{q.text}</span>
              </p>
              <ul className="options-review">
                {q.options.map((option) => (
                  <li key={option} className={q.correct_answers.includes(option) ? 'right' : ''}>
                    {option}
                    {q.correct_answers.includes(option) && ' ✓'}
                  </li>
                ))}
              </ul>
              {q.explanation && <p className="muted small">{q.explanation}</p>}
            </div>
          ))}
          <div className="actions">
            <button type="button" className="secondary" onClick={() => setPreview(null)} disabled={busy !== null}>
              Discard
            </button>
            <button type="button" onClick={save} disabled={busy !== null}>
              {busy === 'save' ? 'Saving…' : `Add these ${preview.questions.length} questions`}
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
